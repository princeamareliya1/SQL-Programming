--10. CREATE INSTEAD OF UPDATE TRIGGER TO PREVENT UPDATING GENDER COLUMN AFTER EMPLOYEE REGISTRATION.
CREATE TRIGGER TRG_PREVENTGENDERUPDATE
ON EMPLOYEE
INSTEAD OF UPDATE
AS
BEGIN
    IF EXISTS
    (
        SELECT 1 FROM INSERTED I
        INNER JOIN DELETED D
            ON I.EID = D.EID
        WHERE ISNULL(I.GENDER, '') <> ISNULL(D.GENDER, '')
    )
    BEGIN
        PRINT 'EMPLOYEE GENDER CANNOT BE CHANGED AFTER REGISTRATION.';
        RETURN;
    END;

    UPDATE E
    SET
        E.FIRSTNAME = I.FIRSTNAME,E.LASTNAME = I.LASTNAME,E.CITY = I.CITY,E.JOININGYEAR = I.JOININGYEAR,E.GENDER = I.GENDER,E.DEPARTMENTNAME = I.DEPARTMENTNAME
    FROM EMPLOYEE E
    INNER JOIN INSERTED I
        ON E.EID = I.EID;
END;