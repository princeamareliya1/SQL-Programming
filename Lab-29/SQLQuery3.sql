        PRINT 'STUDENT SPI CANNOT BE UPDATED.';
        RETURN;
    END;

    UPDATE S
    SET
        S.STUDENTNAME = I.STUDENTNAME,S.BRANCH = I.BRANCH,S.SPI = I.SPI
    FROM STUDENT S
    INNER JOIN INSERTED I
        ON S.SID = I.SID;
END;

--15. CREATE INSTEAD OF UPDATE TRIGGER TO STORE STUDENT BRANCH TRANSFER HISTORY INTO STUDENT_LOG TABLE. 
CREATE TRIGGER TRG_BRANCHTRANSFERHISTORY
ON STUDENT
INSTEAD OF UPDATE
AS
BEGIN
    IF EXISTS
    (
        SELECT 1 FROM INSERTED I
        INNER JOIN DELETED D
            ON I.SID = D.SID
        WHERE ISNULL(I.BRANCH, '') <> ISNULL(D.BRANCH, '')
    )
    BEGIN
        INSERT INTO STUDENT_LOG
        (
            SID,STUDENTNAME,BRANCH,SPI,OPERATION,OPERATIONDATE
        )
        SELECT
            D.SID,D.STUDENTNAME,D.BRANCH,D.SPI,
            'BRANCH TRANSFER FROM ' + D.BRANCH +
            ' TO ' + I.BRANCH,
            GETDATE()
        FROM INSERTED I
        INNER JOIN DELETED D
            ON I.SID = D.SID;
    END;

    UPDATE S
    SET
        S.STUDENTNAME = I.STUDENTNAME,S.BRANCH = I.BRANCH,S.SPI = I.SPI
    FROM STUDENT S
    INNER JOIN INSERTED I
        ON S.SID = I.SID;
END;