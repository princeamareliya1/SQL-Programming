--13. CREATE INSTEAD OF DELETE TRIGGER TO MOVE DELETED STUDENT RECORDS INTO STUDENT_LOG TABLE INSTEAD OF PERMANENT DELETION. 
CREATE TRIGGER TRG_STUDENTDELETELOG
ON STUDENT
INSTEAD OF DELETE
AS
BEGIN
    INSERT INTO STUDENT_LOG
    (
        SID,STUDENTNAME,BRANCH,SPI,OPERATION,OPERATIONDATE
    )
    SELECT
        SID,STUDENTNAME,BRANCH,SPI,'DELETE',GETDATE()
    FROM DELETED;

    PRINT 'DELETED STUDENT RECORD MOVED TO STUDENT_LOG.';
END;

--14. CREATE INSTEAD OF UPDATE TRIGGER TO PREVENT UPDATING STUDENT SPI. 
CREATE TRIGGER TRG_PREVENTSPIUPDATE
ON STUDENT
INSTEAD OF UPDATE
AS
BEGIN
    IF EXISTS
    (
        SELECT 1 FROM INSERTED I
        INNER JOIN DELETED D
            ON I.SID = D.SID
        WHERE ISNULL(I.SPI, -1) <> ISNULL(D.SPI, -1)
    )
