--11. CREATE INSTEAD OF INSERT TRIGGER TO PREVENT INSERTION OF STUDENTS WHOSE SPI IS GREATER THAN 10 OR LESS THAN 0. 
CREATE TRIGGER TRG_PREVENTINVALIDSPI
ON STUDENT
INSTEAD OF INSERT
AS
BEGIN
    IF EXISTS
    (
        SELECT 1 FROM INSERTED
        WHERE SPI > 10 OR SPI < 0
    )
    BEGIN
        PRINT 'SPI MUST BE BETWEEN 0 AND 10.';
        RETURN;
    END;

    INSERT INTO STUDENT
    (
        SID,STUDENTNAME,BRANCH,SPI
    )
    SELECT
        SID,STUDENTNAME,BRANCH,SPI
    FROM INSERTED;
END;

--12. CREATE INSTEAD OF UPDATE TRIGGER TO BLOCK STUDENTS FROM CHANGING THEIR BRANCH AFTER ADMISSION. 
CREATE TRIGGER TRG_PREVENTBRANCHUPDATE
ON STUDENT
INSTEAD OF UPDATE
AS
BEGIN
    IF EXISTS
    (
        SELECT 1 FROM INSERTED I
        INNER JOIN DELETED D
            ON I.SID = D.SID
        WHERE ISNULL(I.BRANCH, '') <> ISNULL(D.BRANCH, '')
    )
    BEGIN
        PRINT 'STUDENT BRANCH CANNOT BE CHANGED AFTER ADMISSION.';
        RETURN;
    END;

    UPDATE S
    SET
        S.STUDENTNAME = I.STUDENTNAME,S.BRANCH = I.BRANCH,S.SPI = I.SPI
    FROM STUDENT S
    INNER JOIN INSERTED I
        ON S.SID = I.SID;
END;
