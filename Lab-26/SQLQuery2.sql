--7. CREATE A TABLE VALUED FUNCTION THAT ACCEPTS CITY AND RETURNS STUDENTS WHOSE SPI IS GREATER THAN 7 FROM THAT CITY. 
CREATE FUNCTION FN_GETSTUDENTBYCITY
(
	@CITY VARCHAR(20)
)
RETURNS TABLE
AS
RETURN
(
	SELECT * FROM STUDENT
	WHERE SPI > 7 AND CITY = @CITY 
);
