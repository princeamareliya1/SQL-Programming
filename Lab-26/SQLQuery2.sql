--8. CREATE A TABLE VALUED FUNCTION THAT ACCEPTS BRANCH AND RETURNS STUDENTS WHOSE SPI IS LESS THAN 8 FROM THAT BRANCH. 
CREATE FUNCTION FN_GETSTUDENTBYBRANCH
(
	@BRANCH VARCHAR(20)
)
RETURNS TABLE
AS
RETURN
(
