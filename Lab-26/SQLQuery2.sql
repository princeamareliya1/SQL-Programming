--9. CREATE A TABLE VALUED FUNCTION THAT ACCEPTS TOPN AND RETURNS TOP N STUDENTS BASED ON SPI. 
CREATE FUNCTION DBO.GETTOPSTUDENTS
(
    @TOPN INT
)
RETURNS TABLE
AS
RETURN
(
    SELECT TOP (@TOPN) STDID,SNAME,CITY,SPI,BRANCH
    FROM STUDENT
    ORDER BY SPI DESC
);
SELECT * FROM DBO.GETTOPSTUDENTS(5);


--10. CREATE A TABLE VALUED FUNCTION THAT ACCEPTS BRANCH AND RETURNS HIGHEST SPI STUDENT FROM THAT BRANCH.
CREATE FUNCTION DBO.GET_HIGHEST_SPI_STUDENT
(
    @BRANCH VARCHAR(50)
)
RETURNS TABLE
AS
RETURN
(
    SELECT TOP 1 STDID,SNAME,CITY,SPI,BRANCH
    FROM STUDENT
    WHERE BRANCH = @BRANCH
    ORDER BY SPI DESC
);
SELECT * FROM DBO.GET_HIGHEST_SPI_STUDENT('COMPUTER');
